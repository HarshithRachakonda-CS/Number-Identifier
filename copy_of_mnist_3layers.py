def train_2layer(Hh=128, epochs=20, lr=0.01, batch_size=256, seed=0):
    rng = np.random.RandomState(seed)
    w1 = rng.randn(784, Hh) * np.sqrt(2./784); c1 = np.zeros(Hh)
    w2 = rng.randn(Hh, 10)  * np.sqrt(2./Hh);  c2 = np.zeros(10)
    n_tr = X_train.shape[0]; t0 = time.time(); accs = []
    for ep in range(epochs):
        p = rng.permutation(n_tr); Xs, ys = X_train[p], y_train[p]
        for i in range(int(np.ceil(n_tr/batch_size))):
            s = i*batch_size; e = min(s+batch_size, n_tr)
            xb, yb = Xs[s:e], ys[s:e]; m = xb.shape[0]
            a1 = np.maximum(0, xb @ w1 + c1)
            lo = a1 @ w2 + c2
            ex = np.exp(lo - lo.max(1, keepdims=True)); pr = ex/ex.sum(1, keepdims=True)
            dl = pr.copy(); dl[range(m), yb] -= 1; dl /= m
            dw2 = a1.T @ dl; dc2 = dl.sum(0)
            dz1 = (dl @ w2.T) * (a1 > 0)
            dw1 = xb.T @ dz1; dc1 = dz1.sum(0)
