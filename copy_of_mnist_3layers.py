def classify_digit(img_base64):
    # Decode base64 image data
    header, encoded = img_base64.split(",", 1)
    data = base64.b64decode(encoded)

    # Load into OpenCV
    nparr = np.frombuffer(data, np.uint8)
    img = cv2.imdecode(nparr, cv2.IMREAD_UNCHANGED)

    # Split channels (extract alpha channel for white-on-black mask, or use RGB average)
    if img.shape[2] == 4:
        # Handdrawn pixels have non-zero alpha
        gray = img[:, :, 3]
    else:
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    # Resize to 28x28 using area interpolation for high-quality downsampling
    resized = cv2.resize(gray, (28, 28), interpolation=cv2.INTER_AREA)

    # Normalize to 0-1 range to match X_train pre-processing
    normalized = resized.astype(np.float32) / 255.0

    # Flatten image to shape (1, 784)
    flattened = normalized.reshape(1, 784)

    # Run through the pre-trained forward pass already in memory
    logits, _, _ = forward(flattened)

    # Prediction
    predicted_digit = int(np.argmax(logits, axis=1)[0])

    return IPython.display.JSON({'predicted_digit': predicted_digit})

