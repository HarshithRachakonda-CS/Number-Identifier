# 1. Load data
train_dataset = MNIST(root='data', train=True, download=True, transform=ToTensor())
test_dataset = MNIST(root='data', train=False, download=True, transform=ToTensor())

X_train = train_dataset.data.numpy().reshape(-1, 28*28).astype(np.float32) / 255.0
y_train = train_dataset.targets.numpy()
X_test = test_dataset.data.numpy().reshape(-1, 28*28).astype(np.float32) / 255.0
y_test = test_dataset.targets.numpy()

# 2. Hyperparameters
input_dim = 784
H1 = 128
H2 = 64
output_dim = 10

lr = 0.01
epochs = 20
batch_size = 256

# 3. Initialize weights
def init_weights(fan_in, fan_out):
    return np.random.randn(fan_in, fan_out) * np.sqrt(2. / fan_in)

W1 = init_weights(input_dim, H1)
b1 = np.zeros(H1)
W2 = init_weights(H1, H2)
b2 = np.zeros(H2)
W3 = init_weights(H2, output_dim)
b3 = np.zeros(output_dim)

# 4. Activation
def relu(x):
    return np.maximum(0, x)

def relu_deriv(x):
    return (x > 0).astype(np.float32)

# 5. Forward pass
def forward(X):
    z1 = X @ W1 + b1
    a1 = relu(z1)
    z2 = a1 @ W2 + b2
    a2 = relu(z2)
    logits = a2 @ W3 + b3
    return logits, a1, a2

# 6. Loss and gradients
def compute_loss_and_gradients(X_batch, y_batch):
    N = X_batch.shape[0]
    logits, a1, a2 = forward(X_batch)

    # Softmax. We subtract the max logits for numerical stability and it will not affect the softmax.
    exp_logits = np.exp(logits - np.max(logits, axis=1, keepdims=True))
    probs = exp_logits / np.sum(exp_logits, axis=1, keepdims=True)

    # Cross-entropy loss
    correct_logprobs = -np.log(probs[range(N), y_batch] + 1e-12)
    loss = np.mean(correct_logprobs)

    # Gradient of loss wrt logits
    dlogits = probs.copy()
    dlogits[range(N), y_batch] -= 1
    dlogits /= N

    # Backprop through layers
    global W1, b1, W2, b2, W3, b3
    dW3 = a2.T @ dlogits
    db3 = np.sum(dlogits, axis=0)

    da2 = dlogits @ W3.T
    dz2 = da2 * relu_deriv(a2)
    dW2 = a1.T @ dz2
    db2 = np.sum(dz2, axis=0)

    da1 = dz2 @ W2.T
    dz1 = da1 * relu_deriv(a1)
    dW1 = X_batch.T @ dz1
    db1 = np.sum(dz1, axis=0)

    grads = {'W1': dW1, 'b1': db1,
             'W2': dW2, 'b2': db2,
             'W3': dW3, 'b3': db3}
    return loss, grads

# 7. Training loop
train_losses = []
test_accuracies = []

num_train = X_train.shape[0]
for epoch in range(epochs):
    # Shuffle training data
    perm = np.random.permutation(num_train)
    X_train_shuffled = X_train[perm]
    y_train_shuffled = y_train[perm]

    epoch_loss = 0.0
    num_batches = int(np.ceil(num_train / batch_size))
    for i in range(num_batches):
        start = i * batch_size
        end = min(start + batch_size, num_train)
        X_batch = X_train_shuffled[start:end]
        y_batch = y_train_shuffled[start:end]

        loss, grads = compute_loss_and_gradients(X_batch, y_batch)

        # Update parameters
        W1 -= lr * grads['W1']
        b1 -= lr * grads['b1']
        W2 -= lr * grads['W2']
        b2 -= lr * grads['b2']
        W3 -= lr * grads['W3']
        b3 -= lr * grads['b3']

        epoch_loss += loss * (end - start)

    avg_epoch_loss = epoch_loss / num_train
    train_losses.append(avg_epoch_loss)

    # Evaluate on test set
    logits_test, _, _ = forward(X_test)
    preds = np.argmax(logits_test, axis=1)
    accuracy = np.mean(preds == y_test)
    test_accuracies.append(accuracy)
    print(f"Epoch {epoch+1}/{epochs} - Train loss: {avg_epoch_loss:.4f}, Test acc: {accuracy*100:.2f}%")

